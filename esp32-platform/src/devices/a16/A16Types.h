#pragma once
#ifdef DEVICE_A16
// Порт из esp32-platform/src/devices/kc868-a16/A16Types.h, СУЖЕН под котельную:
// только то периферийное железо A16, которое реально используется здесь
// (2 счётчика на DI, 2 датчика давления 4-20мА на ADC, 2×DS18B20 на 1-Wire).
// Полная 16-канальная генерика (все DIN/DOUT/4×ADC-режима) убрана — если
// понадобится в будущем, взять обратно из esp32-platform.
#include <Arduino.h>

// ── I2C (PCF8574 реле/входы) ──────────────────────────────────────
#define A16_I2C_SDA     4
#define A16_I2C_SCL     5

// ── Аналоговые входы, 4-20мА (давление) ───────────────────────────
// Реальный физический порядок каналов на плате (проверено на железе,
// НЕ совпадает с "естественным" порядком по документации!):
// CH1, CH3, CH4, CH2 → GPIO 36, 34, 35, 39.
// ВАЖНО: датчик давления ХВС в реальной проводке (и в старом проекте,
// который проверен на этом же железе) сидит на терминале, физически
// разведённом на GPIO34 (это то, что на плате промаркировано как CH3!),
// а не на GPIO39 (CH2), как можно было бы наивно предположить по
// названию канала — старый проект компенсировал это явной перестановкой
// порядка чтения пинов. Датчик давления отопления — на GPIO36 (CH1),
// тут всё как ожидается.
#define A16_ADC_P_HEAT_PIN   36   // ADC CH1
#define A16_ADC_P_WATER_PIN  34   // физически промаркирован CH3, см. выше

// ── 1-Wire (DS18B20: уличный + комнатный) ─────────────────────────
// Подписи сверены с официальной распиновкой KinCony (devices.esphome.io):
// HT1=GPIO32, HT2=GPIO33, HT3=GPIO14. Физически на какой HT-разъём что
// подключено — не важно: программно все 3 шины сканируются одинаково,
// а привязка "какой raw.ow{N}_temp — это улица/дом" настраивается через
// веб (ow_outdoor_index/ow_indoor_index), см. BoilerRoomApp.
#define A16_OW_PIN1     32   // HT1
#define A16_OW_PIN2     33   // HT2
#define A16_OW_PIN3     14   // HT3

// ── PCF8574 адреса ─────────────────────────────────────────────────
#define A16_PCF_DI_0    0x22   // IN1-IN8
#define A16_PCF_DI_1    0x21   // IN9-IN16
#define A16_PCF_OUT_0   0x24   // OT1-OT8  (пока не используется котельной, оставлено на будущее)
#define A16_PCF_OUT_1   0x25   // OT9-OT16

// Привязка счётчиков (см. ТЗ: DI1=вода, DI2=газ)
#define A16_DIN_WATER   0
#define A16_DIN_GAS     1

#define A16_MAX_OW_SENSORS 4

// ============================================================
//  КОНФИГ — сохраняется в /device.json
// ============================================================
struct A16Config {
    uint32_t poll_interval = 1000;   // мс, опрос DI/ADC
};

// ============================================================
//  СОСТОЯНИЕ — runtime
// ============================================================
struct A16State {
    // Цифровые входы (только те, что физически используются, но массив
    // на все 16 — дешёво, и PCF8574 всё равно отдаёт байт целиком)
    bool     din[16]         = {};
    bool     din_prev[16]    = {};
    uint32_t din_counter[16] = {};

    // Цифровые выходы (не используются котельной сейчас, задел на будущее)
    bool dout[16] = {};

    // Давление, 4-20мА — только raw ADC, перевод в мА/бар в BoilerRoomApp
    int adc_raw[2] = {};   // [0]=p_heat, [1]=p_water

    // 1-Wire
    uint8_t  ow_count = 0;
    uint64_t ow_addr[A16_MAX_OW_SENSORS] = {};
    float    ow_temp[A16_MAX_OW_SENSORS] = {};
    bool     ow_ok[A16_MAX_OW_SENSORS]   = {};
};

extern A16Config a16Cfg;
extern A16State  a16State;

#endif // DEVICE_A16
